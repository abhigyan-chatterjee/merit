"""Mirror content/taxonomy.py CATEGORIES into apps/web/src/data/curriculum.ts TOPICS.

The taxonomy is the source of truth for the category list: it decides which topic
slugs the problem bank may use and what each is called. The web bundle kept its
own hand-written copy, and the copy had silently lost a category — a topic with
problems in the bank but no entry here renders in no section, so those problems
are counted in the totals and unreachable in the list page.

Only the TOPICS array is rewritten; VISUALIZERS and every other export below it
are left byte-for-byte alone. Regenerate whenever the taxonomy changes.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from content.taxonomy import CATEGORIES  # noqa: E402

CURRICULUM_TS = REPO_ROOT / "apps" / "web" / "src" / "data" / "curriculum.ts"

HEADER = """// @generated by content/generators/sync_topics_ts.py from content/taxonomy.py.
// Do not hand-edit the TOPICS array: run the generator instead, or the topic
// list drifts from the taxonomy the bank is validated against.
"""


def render_topics() -> str:
    blocks = []
    for category in CATEGORIES:
        blocks.append(
            "  {\n"
            f"    slug: '{category['slug']}',\n"
            f"    title: {_ts_string(category['title'])},\n"
            f"    description: {_ts_string(category['description'])},\n"
            f"    iconName: '{category['icon']}'\n"
            "  },"
        )
    return "export const TOPICS: TopicItem[] = [\n" + "\n".join(blocks) + "\n];\n"


def _ts_string(value: str) -> str:
    """Quote a string with single quotes, escaping only what TypeScript needs."""
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def main() -> int:
    source = CURRICULUM_TS.read_text(encoding="utf-8")

    start = source.index("export const TOPICS: TopicItem[] = [")
    end = source.index("\n];", start) + len("\n];\n")
    updated = source[:start] + render_topics() + source[end:]

    if updated == source:
        print(f"TOPICS already matches the taxonomy ({len(CATEGORIES)} topics)")
        return 0

    CURRICULUM_TS.write_text(updated, encoding="utf-8")
    print(f"wrote {len(CATEGORIES)} topics to {CURRICULUM_TS.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
